const pagesBySlug = new Map(GATE_VALVE_SEO_PAGES.map((page) => [page.slug, page]));

export function getGateValveSeoPage(slug: string): GateValveSeoPage | undefined {
  return pagesBySlug.get(slug);
}

export function getRelatedGateValveSeoPages(page: GateValveSeoPage): GateValveSeoPage[] {
  return GATE_VALVE_SEO_PAGES.filter(
    (candidate) =>
      candidate.series === page.series &&
      candidate.connectionVariant === page.connectionVariant &&
      candidate.pn === page.pn,
  );
}

export function findGateValveCatalogProduct(
  products: PublicCatalogProduct[],
  page: GateValveSeoPage,
): PublicCatalogProduct | undefined {
  const normalizedModel = page.model.toLowerCase();
  return products.find((product) => {
    if (product.category !== "zadvizhki") return false;
    if ((product.model || "").toLowerCase() !== normalizedModel) return false;
    if (product.dn !== page.dn || product.pn !== page.pn) return false;
    if (page.connectionVariant === "welding") {
      return product.connectionType === "Под приварку";
    }
    return product.connectionType !== "Под приварку";
  });
}

function buildGateValvePage(
  template: GateValveTemplate,
  dn: number,
  pn: number,
): GateValveSeoPage {
  const slugParts = [template.series, `dn${dn}`, `pn${pn}`, template.slugSuffix].filter(Boolean);
  const slug = slugParts.join("-");
  const title = template.makeTitle(dn, pn);
  return {
    ...template,
    slug,
    dn,
    pn,
    title,
    h1: title,
    seoTitle: template.makeSeoTitle(dn, pn),
    seoDescription: template.makeSeoDescription(dn, pn),
    imageAlt: title,
    imageFileName: `${slug}.jpg`,
    introParagraphs: template.makeIntroParagraphs(dn, pn),
    characteristics: template.makeCharacteristics(dn, pn),
  };
}
